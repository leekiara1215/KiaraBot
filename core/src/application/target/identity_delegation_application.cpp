IdentityDelegationApplication::IdentityDelegationApplication(
    IdentitySecurityApplication& sessions, IdentitySecurityUnitOfWorkFactory& transactions,
    DelegationCryptoPort& delegations, RandomPort& random, SecurityClockPort& clock,
    IdentityDelegationOptions options)
    : sessions_(sessions), transactions_(transactions), delegations_(delegations), random_(random),
      clock_(clock), options_(std::move(options)) {}

Outcome<IdentityDelegationReply>
IdentityDelegationApplication::issue_delegation(const IssueIdentityDelegationRequest& request) {
  try {
    const auto* control = std::get_if<PlatformPeer>(&request.source.control_peer.binding.peer);
    if (!control || control->service != Service::Control || control->subject.value.empty()) {
      return authentication_rejected();
    }
    if (options_.issuer.empty() || options_.signing_key.value.empty() ||
        !valid_service(request.audience) || request.permissions.empty()) {
      return rejected(ErrorCode::InvalidArgument, Recovery::CorrectInput);
    }
    std::set<std::pair<Permission, ResourceRef>,
             bool (*)(const std::pair<Permission, ResourceRef>&,
                      const std::pair<Permission, ResourceRef>&)>
        unique([](const auto& left, const auto& right) {
          return left.first != right.first ? left.first < right.first
                                           : PolicyResourceLess{}(left.second, right.second);
        });
    for (const auto& permission : request.permissions) {
      if (!known_permission(permission.permission) || !valid_policy_resource(permission.resource) ||
          !unique.emplace(permission.permission, permission.resource).second) {
        return rejected(ErrorCode::InvalidArgument, Recovery::CorrectInput);
      }
    }
    auto validated = sessions_.validate_session(request.source);
    if (const auto* failure = std::get_if<Failure>(&validated)) {
      return *failure;
    }
    const auto authority = [&]() -> Outcome<IssuanceAuthority> {
      auto begun = transactions_.begin();
      if (const auto* failure = std::get_if<Failure>(&begun)) {
        return *failure;
      }
      auto work = std::move(std::get<std::unique_ptr<IdentitySecurityUnitOfWork>>(begun));
      if (!work) {
        return delegation_internal();
      }
      return authorize_issue(*work, request, std::get<ValidatedSession>(validated));
    }();
    if (const auto* failure = std::get_if<Failure>(&authority)) {
      return *failure;
    }
    auto clock = clock_.sample();
    if (const auto* failure = std::get_if<Failure>(&clock)) {
      return *failure;
    }
    const auto& sample = std::get<SecurityClockSample>(clock);
    if (!sample.trusted || sample.maximum_known_skew > kMaximumKnownClockSkew ||
        sample.maximum_known_skew < std::chrono::milliseconds::zero()) {
      return rejected(ErrorCode::UpstreamUnavailable, Recovery::Diagnose);
    }
    const auto& state = std::get<IssuanceAuthority>(authority);
    const auto now = std::max(sample.utc, state.checked_at);
    auto expiry = identity_deadline(now, kDelegationBodyLifetime);
    if (const auto* failure = std::get_if<Failure>(&expiry)) {
      return *failure;
    }
    const auto expires_at = std::min({std::get<TimePoint>(expiry), state.latest_expiry,
                                      request.source.control_peer.binding.certificate.not_after});
    if (expires_at <= now || now >= request.source.context.deadline) {
      return authentication_rejected();
    }
    auto identifier = proof_id(random_);
    if (const auto* failure = std::get_if<Failure>(&identifier)) {
      return *failure;
    }
    DelegationClaims claims{options_.issuer,
                            request.audience,
                            std::get<ValidatedSession>(validated).principal.id,
                            control->subject,
                            {control->subject},
                            request.permissions,
                            std::get<MessageId>(identifier),
                            request.source.control_peer.binding.certificate.fingerprint,
                            std::get<ValidatedSession>(validated).authorization_version,
                            now,
                            now,
                            expires_at,
                            1,
                            state.credential,
                            std::get<ValidatedSession>(validated).session.id};
    const auto shape = validate_delegation_shape(claims);
    if (const auto* failure = std::get_if<Failure>(&shape)) {
      return *failure;
    }
    auto signed_proof = delegations_.sign(claims, options_.signing_key);
    if (const auto* failure = std::get_if<Failure>(&signed_proof)) {
      return *failure;
    }
    if (!std::get<OwnedSecret>(signed_proof) ||
        std::get<OwnedSecret>(signed_proof)->bytes().empty()) {
      return delegation_internal();
    }
    auto current = sessions_.validate_session(request.source);
    if (const auto* failure = std::get_if<Failure>(&current)) {
      return *failure;
    }
    const auto& checked = std::get<ValidatedSession>(current);
    if (checked.authorization_version != claims.authorization_version ||
        checked.principal.id != claims.subject || checked.session.id != claims.source_session ||
        checked.session.version != std::get<ValidatedSession>(validated).session.version ||
        checked.session.rotation != std::get<ValidatedSession>(validated).session.rotation ||
        checked.checked_at >= expires_at || checked.checked_at >= request.source.context.deadline) {
      return authentication_rejected();
    }
    return IdentityDelegationReply{std::move(std::get<OwnedSecret>(signed_proof)),
                                   std::move(claims), checked.checked_at};
  } catch (...) {
    return delegation_internal();
  }
}

