Failure delegation_internal() {
  return rejected(ErrorCode::Internal, Recovery::Diagnose);
}
struct IssuanceAuthority {
  CredentialVersionRef credential;
  TimePoint checked_at;
  TimePoint latest_expiry;
};
Outcome<MessageId> proof_id(RandomPort& random) {
  auto generated = random.bytes(16);
  if (const auto* failure = std::get_if<Failure>(&generated)) {
    return *failure;
  }
  const auto& secret = std::get<OwnedSecret>(generated);
  if (!secret || secret->bytes().size() != 16) {
    return delegation_internal();
  }
  // UUIDv4 formatting only. Entropy is exclusively generated by the injected mature CSPRNG.
  constexpr std::string_view kHex = "0123456789abcdef";
  std::string identifier;
  identifier.reserve(36);
  for (std::size_t index = 0; index < 16; ++index) {
    if (index == 4 || index == 6 || index == 8 || index == 10) {
      identifier.push_back('-');
    }
    auto byte = std::to_integer<unsigned int>(secret->bytes()[index]);
    if (index == 6) {
      byte = (byte & 0x0fU) | 0x40U;
    } else if (index == 8) {
      byte = (byte & 0x3fU) | 0x80U;
    }
    identifier.push_back(kHex[byte >> 4]);
    identifier.push_back(kHex[byte & 0x0fU]);
  }
  return MessageId{std::move(identifier)};
}
Outcome<IssuanceAuthority> authorize_issue(IdentitySecurityUnitOfWork& work,
                                           const IssueIdentityDelegationRequest& request,
                                           const ValidatedSession& validated) {
  const auto sample = work.current_time();
  if (const auto* failure = std::get_if<Failure>(&sample)) {
    return *failure;
  }
  const auto now = std::get<TimePoint>(sample);
  if (now >= request.source.context.deadline) {
    return rejected(ErrorCode::Timeout, Recovery::Backoff);
  }
  auto found = work.session_security().find(validated.session.id);
  if (const auto* failure = std::get_if<Failure>(&found)) {
    return *failure;
  }
  const auto& session = std::get<std::optional<SessionSecurity>>(found);
  if (!session || session->version != validated.session.version ||
      session->rotation != validated.session.rotation ||
      session->subject != validated.principal.id) {
    return authentication_rejected();
  }
  auto principal_row = work.principals().find(session->subject);
  if (const auto* failure = std::get_if<Failure>(&principal_row)) {
    return *failure;
  }
  const auto& principal = std::get<std::optional<Principal>>(principal_row);
  auto credential_row = work.credentials().current(session->credential.id);
  if (const auto* failure = std::get_if<Failure>(&credential_row)) {
    return *failure;
  }
  const auto& credential = std::get<std::optional<CredentialVersionRecord>>(credential_row);
  if (!principal || !credential) {
    return authentication_rejected();
  }
  const auto current =
      require_session_current(*principal, *credential, *session, TokenPurpose::Access, now);
  if (const auto* failure = std::get_if<Failure>(&current)) {
    return *failure;
  }
  const auto read_version = [&]() -> Outcome<AuthorizationState> {
    auto row = work.authorizations().find(principal->id);
    if (const auto* failure = std::get_if<Failure>(&row)) {
      return *failure;
    }
    const auto& state = std::get<std::optional<AuthorizationState>>(row);
    if (!state || state->subject != principal->id || state->version.value == 0) {
      return delegation_internal();
    }
    if (state->version != validated.authorization_version) {
      return rejected(ErrorCode::Conflict, Recovery::ReadCurrent);
    }
    return *state;
  };
  const auto before = read_version();
  if (const auto* failure = std::get_if<Failure>(&before)) {
    return *failure;
  }
  const auto grants = work.exact_assignments().for_subject(principal->id);
  if (const auto* failure = std::get_if<Failure>(&grants)) {
    return *failure;
  }
  const auto& assignments = std::get<std::vector<ExactAssignment>>(grants);
  const auto valid = validate_assignment_collection(assignments, principal->id);
  if (const auto* failure = std::get_if<Failure>(&valid)) {
    return *failure;
  }
  for (const auto& binding : request.permissions) {
    Status allowed;
    if (binding.permission == Permission::IdentitySessionRead &&
        binding.resource.kind == ResourceKind::Principal) {
      allowed =
          authorize_session_list(*principal, SubjectId{binding.resource.id.value}, assignments);
    } else if (binding.permission == Permission::IdentitySessionRevoke &&
               binding.resource.kind == ResourceKind::Session) {
      auto target = work.session_security().find(SessionId{binding.resource.id.value});
      if (const auto* failure = std::get_if<Failure>(&target)) {
        return *failure;
      }
      const auto& owned = std::get<std::optional<SessionSecurity>>(target);
      if (!owned) {
        return rejected(ErrorCode::NotFound, Recovery::CorrectInput);
      }
      allowed = authorize_session_revoke(*principal, session_metadata(*owned), assignments);
    } else {
      allowed = authorize_exact(*principal, binding.permission, binding.resource, assignments);
    }
    if (const auto* failure = std::get_if<Failure>(&allowed)) {
      return *failure;
    }
  }
  const auto after = read_version();
  if (const auto* failure = std::get_if<Failure>(&after)) {
    return *failure;
  }
  return IssuanceAuthority{session->credential, now,
                           std::min(session->access_expires_at, *credential->expires_at)};
}
