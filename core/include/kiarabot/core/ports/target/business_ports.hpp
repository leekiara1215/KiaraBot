// Acceptance result of one inbox transaction. Duplicate means the same event key already holds
// the same fingerprint; a changed fingerprint is Conflict and leaves watermark/targets untouched.
struct EventAcceptanceResult {
  bool duplicate = false;
  SequenceDecision sequence;
  std::size_t targets = 0;
};
struct DeliveryClaimRequest {
  InstanceId instance;
  Fence fence;
  std::size_t limit = 1;
  std::chrono::seconds lease = kDeliveryLease;
  TimePoint now{};
  // Server CSPRNG attempt ids supplied by the owning application (at least limit entries).
  std::vector<AttemptId> attempt_ids;
};
struct DeliveryClaim {
  DeliveryAttempt attempt;
  EventRecord event;
  std::string trace_id;
  bool ordered = false;
};
struct DeliveryAcknowledgement {
  DeliveryAttempt attempt;
  bool accepted = false;
  std::optional<Failure> failure;
  // Wire Error.retryable: a rejected delivery is retried only when the plugin says retryable.
  bool retryable = false;
  RetryPolicy retry;
  double jitter_sample = 0.5;
};
struct DeliverySweep {
  std::size_t expired_attempts = 0;
  std::size_t dead_lettered = 0;
  std::size_t retrying = 0;
};
struct ReplayRequest {
  DeliveryKey delivery;
  // Generated by the owning application (server CSPRNG id); the repository never invents ids.
  OperationId operation;
  std::string trace_id;
  TimePoint now{};
};

// Runtime event inbox / per-instance delivery ledger. All methods participate in the caller's
// Runtime UoW, never open/commit another transaction and never perform remote calls.
class EventRepository {
public:
  virtual ~EventRepository() = default;
  // Insert event + watermark + fan-out targets atomically. Capacity is checked in the same
  // transaction; saturation rejects the whole acceptance without partial targets.
  virtual Outcome<EventAcceptanceResult> accept(const EventRecord& event,
                                                const std::vector<DeliveryRecord>& targets,
                                                const EventCapacityLimits& limits) = 0;
  // Claim up to limit due targets for one registered instance. Ordered groups only yield their
  // earliest non-terminal target; every claim persists a new attempt (new attempt id, fence,
  // started_at, lease_until) before returning.
  virtual Outcome<std::vector<DeliveryClaim>> claim(const DeliveryClaimRequest& request) = 0;
  // Look up the durable attempt by the authenticated owner and complete wire attempt identity.
  // Empty means absent/invisible; dependency errors remain Failure. This read retains the owner
  // instance and delivery-target locks until this UoW ends so the application can verify the
  // current fence and then call acknowledge/renew without a concurrent generation/state change. It
  // does not authorize the request or classify a duplicate; ACK/Renew still adjudicate the ledger.
  virtual Outcome<std::optional<DeliveryAttempt>>
  find_attempt(const InstanceId& instance, std::string_view event_id, const AttemptId& attempt) = 0;
  // ACK maps to DELIVERY_ACKNOWLEDGED/DUPLICATE/STALE/REJECTED; a rejected retryable error
  // schedules backoff and a non-retryable/exhausted error dead-letters in the same transaction.
  virtual Outcome<DeliveryReceipt> acknowledge(const DeliveryAcknowledgement& acknowledgement,
                                               TimePoint now) = 0;
  // Renew only extends the current non-expired attempt to min(now+30s, started_at+300s).
  virtual Outcome<DeliveryReceipt> renew(const DeliveryAttempt& attempt, TimePoint now) = 0;
  // Expire dispatcher attempts whose lease elapsed and apply one retryable failure each.
  virtual Outcome<DeliverySweep> sweep(TimePoint now, const RetryPolicy& policy,
                                       double jitter_sample) = 0;
  // Startup recovery: every Dispatched target becomes one retryable failure after the old
  // dispatcher is known stopped; never touches acknowledged/dead-letter rows.
  virtual Outcome<std::size_t> recover(TimePoint now, const RetryPolicy& policy,
                                       double jitter_sample) = 0;
  virtual Outcome<std::vector<DeadLetter>>
  list_dead_letters(const std::optional<InstanceId>& instance, std::size_t limit) = 0;
  // Reset one dead-letter target for replay: keeps event id, clears attempts/current attempt,
  // schedules immediately and records the operation reference in the journal.
  virtual Outcome<std::optional<DeliveryRecord>> replay(const ReplayRequest& request) = 0;
  virtual Outcome<EventCapacity> capacity(const EventCapacityLimits& limits) = 0;
  // Delete terminal events (and their targets/attempts) past retain_until; bounded batch.
  virtual Outcome<std::size_t> prune_expired(TimePoint now, std::size_t limit) = 0;
};
// Draft P07a persistence ports. The Runtime application owns policy/authorization; these ports
// only adjudicate durable row state in the caller's Runtime UoW (no network, no second commit).
// All temporal predicates are rechecked against database UTC inside the implementation; TimePoint
// arguments are application samples, never lease authorities.
struct ActionCapacity {
  // Trusted deployment limits, never request-controlled.
  std::size_t max_pending_per_owner = 1024;
  std::size_t max_records = 100000;
};
struct ActionPageRequest {
  std::size_t limit = 20;
  std::string after_action_id;
};
struct ActionControlQuery {
  ResourceScope scope;
  std::optional<ActionState> state;
  std::optional<ActionKind> kind;
  ActionPageRequest page;
};
struct ActionTerminalReceipt {
  ActionReceiptDisposition disposition = ActionReceiptDisposition::Recorded;
  ActionRecord record;
  bool evidence_appended = false;
};
struct ActionEvidenceRecord {
  ActionId action_id;
  AttemptId dispatch_attempt_id;
  InstanceId adapter_instance;
  ActionEvidenceKind kind = ActionEvidenceKind::Unknown;
  ExecutionOutcome execution_outcome = ExecutionOutcome::Unknown;
  std::optional<ErrorCode> error_code;
  std::optional<std::string> platform_reference;
  TimePoint observed_at;
  TimePoint received_at;
  TimePoint retain_until;
};

// One authoritative Action row per (owner, idempotency key). insert is create-only; the caller
// resolves idempotent replay/conflict through find_by_owner_key before deciding to insert. Quota
// admission and the Action row are part of the same UoW and fixed lock order.
class ActionRepository {
public:
  virtual ~ActionRepository() = default;
  virtual Outcome<std::optional<ActionRecord>> find_by_id(const ActionId& action_id) = 0;
  virtual Outcome<std::optional<ActionRecord>>
  find_by_owner_key(const InstanceId& owner, std::string_view idempotency_key) = 0;
  // Inserts the admitted row; a duplicate (owner,idempotency_key)/(dispatch_attempt_id) or
  // capacity exhaustion is never partially written and surfaces Conflict/RateLimited.
  virtual Outcome<ActionRecord> insert(const ActionRecord& record, ActionCapacity capacity) = 0;
  // Conditional update: only Accepted+NotDispatched and now<deadline; persists attempt id,
  // sequence and dispatched instance atomically (Conflict otherwise).
  virtual Status mark_dispatched(const ActionId& action_id, const AttemptId& attempt_id,
                                 const InstanceId& adapter_instance, TimePoint now) = 0;
  // Applies the domain terminal/evidence decision; duplicate/conflict/late results never rewrite
  // a known terminal row. The returned record is the persisted authoritative snapshot.
  virtual Outcome<ActionTerminalReceipt> record_terminal(const ActionRecord& current,
                                                         const ActionTerminalResult& result,
                                                         std::optional<AttemptId> attempt_id,
                                                         std::optional<InstanceId> adapter_instance,
                                                         TimePoint now) = 0;
  // Cancel only when Accepted+NotDispatched; dispatched/terminal rows Conflict and keep state.
  virtual Status cancel(const ActionId& action_id, TimePoint now) = 0;
  // Claims up to limit accepted actions whose deadline elapsed; each row becomes terminal in the
  // same conditional update and the returned records carry the authoritative outcome.
  virtual Outcome<std::vector<ActionRecord>> expire_due(std::size_t limit, TimePoint now) = 0;
  virtual Outcome<std::vector<ActionRecord>> list_owner(const InstanceId& owner,
                                                        const ActionPageRequest& page) = 0;
  virtual Outcome<std::vector<ActionRecord>> list_control(const ActionControlQuery& query) = 0;
  // Bounded dispatch claim source for the bridge: accepted, not-dispatched rows targeting this
  // adapter resource whose deadline is still in the future. The caller marks each row dispatched
  // in the same UoW; the rows are selected FOR UPDATE SKIP LOCKED by the PG adapter.
  virtual Outcome<std::vector<ActionRecord>> list_due(const ResourceId& adapter_id,
                                                      std::size_t limit, TimePoint now) = 0;
  // Removes only terminal rows whose retain_until elapsed; pending/unknown rows are never pruned.
  virtual Outcome<std::size_t> prune_terminal(TimePoint now, std::size_t limit) = 0;
};
// Persistent sliding-window occupancy + UTC-day budget. admit must be called in the same UoW as
// the Action insert; it never refunds explicit failures/cancels/expiry (conservative budgets).
class ActionQuotaRepository {
public:
  virtual ~ActionQuotaRepository() = default;
  virtual Status admit(const ActionId& action_id, ActionKind kind,
                       std::span<const ActionScope> scopes, const ActionQuotaLimits& limits,
                       TimePoint now) = 0;
  virtual Outcome<std::size_t> prune_windows(TimePoint now, std::size_t limit) = 0;
};
class ActionPolicyRepository {
public:
  virtual ~ActionPolicyRepository() = default;
  virtual Outcome<std::optional<ActionPolicy>> get(const ResourceId& account_id) = 0;
  // expected absent = create-only (version must be 0); present = exact-version update/upsert.
  virtual Status upsert(const ActionPolicy& policy, std::optional<ResourceVersion> expected) = 0;
};
