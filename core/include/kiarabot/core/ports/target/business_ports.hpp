// Acceptance result of one inbox transaction. Duplicate means the same event key already holds
// the same fingerprint; a changed fingerprint is Conflict and leaves watermark/targets untouched.
struct EventAcceptanceResult {
  bool duplicate = false;
  SequenceDecision sequence;
  std::size_t targets = 0;
};
struct DeliveryClaimRequest {
  InstanceId instance;
  Fence fence;
  std::size_t limit = 1;
  std::chrono::seconds lease = kDeliveryLease;
  TimePoint now{};
  // Server CSPRNG attempt ids supplied by the owning application (at least limit entries).
  std::vector<AttemptId> attempt_ids;
};
struct DeliveryClaim {
  DeliveryAttempt attempt;
  EventRecord event;
  std::string trace_id;
  bool ordered = false;
};
struct DeliveryAcknowledgement {
  DeliveryAttempt attempt;
  bool accepted = false;
  std::optional<Failure> failure;
  // Wire Error.retryable: a rejected delivery is retried only when the plugin says retryable.
  bool retryable = false;
  RetryPolicy retry;
  double jitter_sample = 0.5;
};
struct DeliverySweep {
  std::size_t expired_attempts = 0;
  std::size_t dead_lettered = 0;
  std::size_t retrying = 0;
};
struct ReplayRequest {
  DeliveryKey delivery;
  // Generated by the owning application (server CSPRNG id); the repository never invents ids.
  OperationId operation;
  std::string trace_id;
  TimePoint now{};
};

// Runtime event inbox / per-instance delivery ledger. All methods participate in the caller's
// Runtime UoW, never open/commit another transaction and never perform remote calls.
class EventRepository {
public:
  virtual ~EventRepository() = default;
  // Insert event + watermark + fan-out targets atomically. Capacity is checked in the same
  // transaction; saturation rejects the whole acceptance without partial targets.
  virtual Outcome<EventAcceptanceResult> accept(const EventRecord& event,
                                                const std::vector<DeliveryRecord>& targets,
                                                const EventCapacityLimits& limits) = 0;
  // Claim up to limit due targets for one registered instance. Ordered groups only yield their
  // earliest non-terminal target; every claim persists a new attempt (new attempt id, fence,
  // started_at, lease_until) before returning.
  virtual Outcome<std::vector<DeliveryClaim>> claim(const DeliveryClaimRequest& request) = 0;
  // ACK maps to DELIVERY_ACKNOWLEDGED/DUPLICATE/STALE/REJECTED; a rejected retryable error
  // schedules backoff and a non-retryable/exhausted error dead-letters in the same transaction.
  virtual Outcome<DeliveryReceipt> acknowledge(const DeliveryAcknowledgement& acknowledgement,
                                               TimePoint now) = 0;
  // Renew only extends the current non-expired attempt to min(now+30s, started_at+300s).
  virtual Outcome<DeliveryReceipt> renew(const DeliveryAttempt& attempt, TimePoint now) = 0;
  // Expire dispatcher attempts whose lease elapsed and apply one retryable failure each.
  virtual Outcome<DeliverySweep> sweep(TimePoint now, const RetryPolicy& policy,
                                       double jitter_sample) = 0;
  // Startup recovery: every Dispatched target becomes one retryable failure after the old
  // dispatcher is known stopped; never touches acknowledged/dead-letter rows.
  virtual Outcome<std::size_t> recover(TimePoint now, const RetryPolicy& policy,
                                       double jitter_sample) = 0;
  virtual Outcome<std::vector<DeadLetter>>
  list_dead_letters(const std::optional<InstanceId>& instance, std::size_t limit) = 0;
  // Reset one dead-letter target for replay: keeps event id, clears attempts/current attempt,
  // schedules immediately and records the operation reference in the journal.
  virtual Outcome<std::optional<DeliveryRecord>> replay(const ReplayRequest& request) = 0;
  virtual Outcome<EventCapacity> capacity(const EventCapacityLimits& limits) = 0;
  // Delete terminal events (and their targets/attempts) past retain_until; bounded batch.
  virtual Outcome<std::size_t> prune_expired(TimePoint now, std::size_t limit) = 0;
};
enum class ActionKind {
  SendMessage,
  ReactMessage,
  DeleteMessage,
  MuteMember,
  KickMember,
  ApproveRequest
};
struct QuotaReservation {
  std::string action_id;
  InstanceId owner;
  ActionKind kind;
  ConversationKey conversation;
  TimePoint accepted_at;
};
class ActionQuotaRepository {
public:
  virtual ~ActionQuotaRepository() = default;
  // Action + receipt + quota + budget + audit must commit together; duplicates never charge twice.
  virtual Status reserve(const QuotaReservation& reservation) = 0;
};
struct PrivateNamespace {
  InstanceId instance;
};
struct SharedNamespace {
  InstallationId installation;
  ResourceId shared_namespace;
};
using NamespaceScope = std::variant<PrivateNamespace, SharedNamespace>;
struct ExpectedAbsent {};
using CompareCondition = std::variant<ExpectedAbsent, ResourceVersion>;
struct NamespaceValue {
  std::vector<std::byte> bytes;
  ResourceVersion version;
  std::optional<TimePoint> expires_at;
};
class NamespaceRepository {
public:
  virtual ~NamespaceRepository() = default;
  virtual Outcome<std::optional<NamespaceValue>> get(const NamespaceScope& scope,
                                                     const std::string& key, TimePoint now) = 0;
  // Scope is server-resolved after authorization; CAS/membership/quota/receipt share the UoW.
  virtual Outcome<ResourceVersion> compare_exchange(const NamespaceScope& scope,
                                                    const std::string& key,
                                                    const CompareCondition& expected,
                                                    const NamespaceValue& value) = 0;
};
class OccurrenceRepository {
public:
  virtual ~OccurrenceRepository() = default;
  virtual Status prepare(const Occurrence& occurrence) = 0;
  // Only persistent Runtime acceptance permits Scheduler completion.
  virtual Status confirm_accepted(const MessageId& occurrence) = 0;
};
class ModelIntentRepository {
public:
  virtual ~ModelIntentRepository() = default;
  virtual Outcome<std::optional<ModelIntent>> find(const InstanceId& owner,
                                                   const std::string& call_id) = 0;
  // Persist Started before Provider invocation; repeats never authorize another invocation.
  virtual Status insert(const ModelIntent& intent) = 0;
  virtual Status record_outcome(const InstanceId& owner, const std::string& call_id,
                                ModelCallState outcome) = 0;
};
