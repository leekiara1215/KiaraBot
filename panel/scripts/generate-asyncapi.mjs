import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { Parser } from '@asyncapi/parser';
import { TypeScriptGenerator } from '@asyncapi/modelina';
const source = resolve('../api/asyncapi.yaml');
const result = await new Parser().parse(await readFile(source, 'utf8'), { source });
const errors = result.diagnostics.filter((diagnostic) => diagnostic.severity === 0);
if (errors.length || !result.document) throw new Error(JSON.stringify(errors));
const models = await new TypeScriptGenerator({ modelType: 'interface', enumType: 'union', rawPropertyNames: true, mapType: 'record' }).generate(result.document);
await writeFile('src/generated/asyncapi.ts', `// Generated by Modelina from api/asyncapi.yaml. Do not edit.\n${models.map((model) => `export ${model.result}`).join('\n\n')}\n`);
